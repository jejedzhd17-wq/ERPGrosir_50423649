    public DashboardFrame(String username, String role) {
        initComponents();
        setTitle("ERP-Grosir - Dashboard " + role);
        pnlKonten.add(new PanelBeranda(username, role), "Dashboard");
        switch (role) {
            case "Admin" -> {
                pnlKonten.add(new PanelBarang(), "Data Barang");
                javax.swing.JTabbedPane tab = new javax.swing.JTabbedPane();
                tab.addTab("Pelanggan", new PanelPelanggan());
                tab.addTab("Supplier", new PanelSupplier());
                pnlKonten.add(tab, "Data Pelanggan dan Supplier");
                pnlKonten.add(new PanelKas(), "Data Kas");
                pnlKonten.add(new PanelLaporan(), "Laporan");
                pnlKonten.add(new PanelPengguna(), "Kelola Pengguna");
                hapusMenu(btnPenjualan, btnFaktur, btnPembelian, btnPenerimaan, btnStok);
            }
            case "Kasir" -> {
                pnlKonten.add(new PanelPenjualan(), "Transaksi Penjualan");
                pnlKonten.add(new PanelFaktur(), "Faktur Penjualan");
                hapusMenu(btnBarang, btnPelangganSupplier, btnKas, btnLaporan, btnPengguna, btnPembelian, btnPenerimaan, btnStok);
            }
            case "Gudang" -> {
                pnlKonten.add(new PanelPembelian(), "Pembelian Barang");
                pnlKonten.add(new PanelPenerimaan(), "Penerimaan Barang");
                pnlKonten.add(new PanelStok(), "Stok Barang");
                hapusMenu(btnBarang, btnPelangganSupplier, btnKas, btnLaporan, btnPengguna, btnPenjualan, btnFaktur);
            }
        }
        setSize(1000, 620);
        setLocationRelativeTo(null);
    }

    private void tampil(String halaman) {
        ((java.awt.CardLayout) pnlKonten.getLayout()).show(pnlKonten, halaman);
    }

    // menu yang bukan milik role dibuang dari panel menu
    private void hapusMenu(javax.swing.JButton... tombol) {
        for (javax.swing.JButton b : tombol) {
            pnlMenu.remove(b);
        }
    }

